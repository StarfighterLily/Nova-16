#!/usr/bin/env python3
"""
NoBASIC Compiler
Compiles NoBASIC programs to Nova-16 assembly with register allocation and spilling.
"""

import re
import sys
from typing import Dict, List, Tuple, Optional, Set
from enum import Enum


class VariableType(Enum):
    NUMBER = "number"  # 16-bit integer
    STRING = "string"
    LIST = "list"


class Variable:
    def __init__(self, name: str, var_type: VariableType, size: int = 1):
        self.name = name
        self.type = var_type
        self.size = size  # For lists, strings, etc.
        self.register = None  # Assigned register or None if spilled
        self.memory_addr = None  # Zero-page address if spilled


class RegisterAllocator:
    def __init__(self):
        # Available registers (reserve P0, P1 for temp operations)
        self.r_registers = [f"R{i}" for i in range(10)]  # 8-bit
        self.p_registers = [f"P{i}" for i in range(2, 10)]  # 16-bit, skip P0, P1

        # Used registers
        self.used_r = set()
        self.used_p = set()

        # Zero-page memory for spilling (0x0000-0x00FF)
        self.zero_page_used = set()  # Occupied addresses
        self.next_zero_page_addr = 0x0000

    def allocate_register(self, is_16bit: bool = False) -> Optional[str]:
        """Allocate a register, or return None if none available"""
        if is_16bit:
            available = [r for r in self.p_registers if r not in self.used_p]
            if available:
                reg = available[0]
                self.used_p.add(reg)
                return reg
        else:
            available = [r for r in self.r_registers if r not in self.used_r]
            if available:
                reg = available[0]
                self.used_r.add(reg)
                return reg
        return None

    def spill_to_zero_page(self, is_16bit: bool = False) -> int:
        """Allocate space in zero-page for spilling"""
        if is_16bit:
            # Need 2 bytes
            addr = self.next_zero_page_addr
            if addr + 1 >= 0x0100:
                raise MemoryError("Zero-page memory exhausted")
            self.zero_page_used.add(addr)
            self.zero_page_used.add(addr + 1)
            self.next_zero_page_addr += 2
            return addr
        else:
            # 1 byte
            addr = self.next_zero_page_addr
            if addr >= 0x0100:
                raise MemoryError("Zero-page memory exhausted")
            self.zero_page_used.add(addr)
            self.next_zero_page_addr += 1
            return addr

    def free_register(self, reg: str):
        """Free a register"""
        if reg.startswith('P'):
            self.used_p.discard(reg)
        elif reg.startswith('R'):
            self.used_r.discard(reg)


class NoBASICCompiler:
    def __init__(self):
        self.variables: Dict[str, Variable] = {}
        self.register_allocator = RegisterAllocator()
        self.output_lines: List[str] = []

    def compile(self, source: str) -> str:
        """Compile NoBASIC source to assembly"""
        # Parse and process
        lines = source.strip().split('\n')
        for line in lines:
            line = line.strip()
            if not line or line.startswith('//'):
                continue
            self.process_line(line)

        # Generate assembly
        return self.generate_assembly()

    def process_line(self, line: str):
        """Process a single line of NoBASIC"""
        # Simple parsing for now - handle assignments
        if '=' in line:
            var_name, expr = line.split('=', 1)
            var_name = var_name.strip()
            expr = expr.strip()
            self.handle_assignment(var_name, expr)

    def handle_assignment(self, var_name: str, expr: str):
        """Handle variable assignment"""
        # Create variable if not exists
        if var_name not in self.variables:
            self.variables[var_name] = Variable(var_name, VariableType.NUMBER)

        var = self.variables[var_name]

        # Try to allocate register
        reg = self.register_allocator.allocate_register(is_16bit=True)
        if reg:
            var.register = reg
            # Generate MOV instruction (simplified)
            self.output_lines.append(f"MOV {reg}, {expr}")
        else:
            # Spill to zero page
            addr = self.register_allocator.spill_to_zero_page(is_16bit=True)
            var.memory_addr = addr
            # Generate store to memory
            self.output_lines.append(f"MOV P0, {expr}")  # Load value into temp
            self.output_lines.append(f"MOV P1, {addr}")  # Load address into temp
            self.output_lines.append(f"MOV [P1], P0")    # Store value to memory

    def generate_assembly(self) -> str:
        """Generate final assembly code"""
        lines = ["; Generated by NoBASIC Compiler", ""]
        lines.extend(self.output_lines)
        lines.append("")  # HALT or something
        return '\n'.join(lines)


def main():
    if len(sys.argv) != 2:
        print("Usage: python nobasic_compiler.py <input.nobasic>")
        sys.exit(1)

    input_file = sys.argv[1]
    output_file = input_file.replace('.nobasic', '.asm')

    with open(input_file, 'r') as f:
        source = f.read()

    compiler = NoBASICCompiler()
    assembly = compiler.compile(source)

    with open(output_file, 'w') as f:
        f.write(assembly)

    print(f"Compiled {input_file} to {output_file}")


if __name__ == "__main__":
    main()