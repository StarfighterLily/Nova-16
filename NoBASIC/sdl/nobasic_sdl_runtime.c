/* Draw line from (x1,y1) to (x2,y2) with color using Bresenham's algorithm */
void nobasic_line(int16_t x1, int16_t y1, int16_t x2, int16_t y2, int16_t color) {
    int16_t x1c = x1 < 0 ? 0 : (x1 >= NOVA_WIDTH ? NOVA_WIDTH - 1 : x1);
    int16_t y1c = y1 < 0 ? 0 : (y1 >= NOVA_HEIGHT ? NOVA_HEIGHT - 1 : y1);
    int16_t x2c = x2 < 0 ? 0 : (x2 >= NOVA_WIDTH ? NOVA_WIDTH - 1 : x2);
    int16_t y2c = y2 < 0 ? 0 : (y2 >= NOVA_HEIGHT ? NOVA_HEIGHT - 1 : y2);
    
    int16_t dx = x2c - x1c;
    int16_t dy = y2c - y1c;
    int16_t sx = (dx >= 0) ? 1 : -1;
    int16_t sy = (dy >= 0) ? 1 : -1;
    int16_t adx = (dx < 0) ? -dx : dx;
    int16_t ady = (dy < 0) ? -dy : dy;
    
    int16_t err, e2;
    int16_t x = x1c, y = y1c;
    
    uint8_t (*target)[NOVA_WIDTH] = get_target_layer();
    uint8_t col = (uint8_t)(color & 0xFF);
    
    if (adx > ady) {
        err = adx / 2;
        for (e2 = 0; e2 < adx; e2++) {
            target[y][x] = col;
            if (x == x2c) break;
            err -= ady;
            if (err < 0) {
                y += sy;
                err += adx;
            }
            x += sx;
        }
    } else {
        err = ady / 2;
        for (e2 = 0; e2 < ady; e2++) {
            target[y][x] = col;
            if (y == y2c) break;
            err -= adx;
            if (err < 0) {
                x += sx;
                err += ady;
            }
            y += sy;
        }
    }
    target[y2c][x2c] = col;
}

/* Draw filled circle centered at (x,y) with radius and color */
void nobasic_circle(int16_t cx, int16_t cy, int16_t radius, int16_t color) {
    int16_t x = 0;
    int16_t y = radius;
    
    int16_t cxc = (cx < 0) ? 0 : ((cx >= NOVA_WIDTH) ? NOVA_WIDTH - 1 : cx);
    int16_t cyc = (cy < 0) ? 0 : ((cy >= NOVA_HEIGHT) ? NOVA_HEIGHT - 1 : cy);
    uint8_t col = (uint8_t)(color & 0xFF);
    uint8_t (*target)[NOVA_WIDTH] = get_target_layer();
    
    while (x >= y) {
        if (cxc + x < NOVA_WIDTH && cyc + y < NOVA_HEIGHT && cxc + x >= 0 && cyc + y >= 0)
            target[cyc + y][cxc + x] = col;
        if (cxc + y < NOVA_WIDTH && cyc + x < NOVA_HEIGHT && cxc + y >= 0 && cyc + x >= 0)
            target[cyc + x][cxc + y] = col;
        if (cxc - y >= 0 && cyc + x < NOVA_HEIGHT && cxc - y < NOVA_WIDTH && cyc + x >= 0)
            target[cyc + x][cxc - y] = col;
        if (cxc - x >= 0 && cyc + y < NOVA_HEIGHT && cxc - x < NOVA_WIDTH && cyc + y >= 0)
            target[cyc + y][cxc - x] = col;
        if (cxc + x < NOVA_WIDTH && cyc - y >= 0 && cxc + x >= 0 && cyc - y < NOVA_HEIGHT)
            target[cyc - y][cxc + x] = col;
        if (cxc + y < NOVA_WIDTH && cyc - x >= 0 && cxc + y >= 0 && cyc - x < NOVA_HEIGHT)
            target[cyc - x][cxc + y] = col;
        if (cxc - y >= 0 && cyc - x >= 0 && cxc - y < NOVA_WIDTH && cyc - x < NOVA_HEIGHT)
            target[cyc - x][cxc - y] = col;
        if (cxc - x >= 0 && cyc - y >= 0 && cxc - x < NOVA_WIDTH && cyc - y < NOVA_HEIGHT)
            target[cyc - y][cxc - x] = col;
        
        y += 1;
        int16_t err = 1 + 2 * y;
        if (2 * (err - x) + 1 > 0) {
            x += 1;
        }
    }
}

/* Draw text at (x, y) with string and color using 8x8 bitmap font */
void nobasic_text(int16_t x, int16_t y, const char *str, int16_t color) {
    if (!str) return;
    
    int16_t col = color & 0xFF;
    int16_t cur_x = x;
    uint8_t (*target)[NOVA_WIDTH] = get_target_layer();
    
    for (const char *p = str; *p; p++) {
        unsigned char ch = (unsigned char)*p;
        
        /* Skip newlines */
        if (ch == '\n') {
            cur_x = x;
            y += 8;
            continue;
        }
        if (ch == '\r') {
            cur_x = x;
            continue;
        }
        
        /* Render character using bitmap font */
        const uint8_t *glyph = get_font_glyph(ch);
        for (int dy = 0; dy < 8; dy++) {
            uint8_t glyph_byte = glyph[dy];
            for (int dx = 0; dx < 8; dx++) {
                if (y + dy < NOVA_HEIGHT && cur_x + dx < NOVA_WIDTH) {
                    if (glyph_byte & font_bit_positions[dx]) {
                        target[y + dy][cur_x + dx] = col;
                    }
                }
            }
        }
        cur_x += 8;
        
        if (cur_x + 8 > NOVA_WIDTH) {
            cur_x = x;
            y += 8;
        }
    }
}

