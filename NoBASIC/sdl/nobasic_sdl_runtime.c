/* Get the current target layer buffer */
static uint8_t (*get_target_layer(void))[NOVA_WIDTH] {
    if (g_current_layer < 0 || g_current_layer > 8) {
        g_current_layer = 0;
    }
    return g_layers[g_current_layer];
}

/* Initialize SDL graphics - creates window and renderer */
int nobasic_gfx_init(void) {
    int result;
    
    result = SDL_Init(SDL_INIT_VIDEO | SDL_INIT_EVENTS);
    if (result < 0) {
        return -1;
    }
    
    /* Create 256x256 window scaled 3x = 768x768 */
    g_window = SDL_CreateWindow("NoBASIC SDL Runtime",
        SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED,
        NOVA_WIDTH * NOVA_SCALE, NOVA_HEIGHT * NOVA_SCALE,
        SDL_WINDOW_SHOWN);
    if (!g_window) {
        SDL_Quit();
        return -1;
    }
    
    /* Create renderer */
    g_renderer = SDL_CreateRenderer(g_window, -1, SDL_RENDERER_ACCELERATED);
    if (!g_renderer) {
        SDL_DestroyWindow(g_window);
        SDL_Quit();
        return -1;
    }
    
    /* Create texture for pixel buffer - use ARGB8888 for wide compatibility */
    g_texture = SDL_CreateTexture(g_renderer, SDL_PIXELFORMAT_ARGB8888, 
        SDL_TEXTUREACCESS_STREAMING, NOVA_WIDTH, NOVA_HEIGHT);
    if (!g_texture) {
        SDL_DestroyRenderer(g_renderer);
        SDL_DestroyWindow(g_window);
        SDL_Quit();
        return -1;
    }
    
    /* Initialize palette */
    init_palette();
    
    /* Clear all layers */
    memset(g_layers, 0, sizeof(g_layers));
    
    return 0;
}

/* Shutdown SDL graphics */
void nobasic_gfx_shutdown(void) {
    if (g_texture) {
        SDL_DestroyTexture(g_texture);
        g_texture = NULL;
    }
    if (g_renderer) {
        SDL_DestroyRenderer(g_renderer);
        g_renderer = NULL;
    }
    if (g_window) {
        SDL_DestroyWindow(g_window);
        g_window = NULL;
    }
    SDL_Quit();
}

/* Present the frame buffer to the screen */
void nobasic_gfx_present(void) {
    if (!g_renderer || !g_texture) {
        return;
    }
    
    /* Composite layers: layer 0 as base, then 1-4, then 5-8 */
    uint8_t composite[NOVA_HEIGHT][NOVA_WIDTH];
    memcpy(composite, g_layers[0], sizeof(composite));
    
    for (int layer = 1; layer < 9; layer++) {
        for (int y = 0; y < NOVA_HEIGHT; y++) {
            for (int x = 0; x < NOVA_WIDTH; x++) {
                if (g_layers[layer][y][x] != 0) {
                    composite[y][x] = g_layers[layer][y][x];
                }
            }
        }
    }
    
    /* Update texture with composite pixels - convert to ARGB8888 */
    void *pixels;
    int pitch;
    if (SDL_LockTexture(g_texture, NULL, &pixels, &pitch) == 0) {
        uint32_t *dst = (uint32_t *)pixels;
        for (int y = 0; y < NOVA_HEIGHT; y++) {
            for (int x = 0; x < NOVA_WIDTH; x++) {
                uint8_t color_idx = composite[y][x];
                SDL_Color col = nova_palette[color_idx & 0xFF];
                dst[y * NOVA_WIDTH + x] = (uint32_t)(col.a << 24) | (col.b << 16) | (col.g << 8) | col.r;
            }
        }
        SDL_UnlockTexture(g_texture);
        
        /* Render scaled */
        SDL_RenderCopy(g_renderer, g_texture, NULL, NULL);
        SDL_RenderPresent(g_renderer);
    }
}

/* Clear the current graphics layer */
void nobasic_clrdraw(void) {
    uint8_t (*target)[NOVA_WIDTH] = get_target_layer();
    memset(target, 0, NOVA_HEIGHT * NOVA_WIDTH);
}

